async function seedNews() {
  try {
    await mongoose.connect(process.env.MONGO_URI);
    console.log('✅ Подключено к MongoDB');

    // Найти админа
    let author = await User.findOne({ role: 'admin' });
    if (!author) {
      console.log('⚠️ Админ не найден, создаём системного пользователя...');
      author = await User.create({
        email: 'system@ecodrug.ru',
        username: 'ecodrug_system',
        password: 'SystemUser123!',
        role: 'admin'
      });
    }

    console.log(`📝 Используем автора: ${author.username}`);

    // Удалить старые новости (опционально)
    const existingCount = await News.countDocuments();
    if (existingCount > 0) {
      console.log(`⚠️ Найдено ${existingCount} существующих новостей. Пропускаем создание.`);
      console.log('   Если хотите пересоздать, удалите их вручную в БД.');
      process.exit(0);
    }

    // Добавить автора к новостям
    const newsWithAuthor = ecologyNews.map(news => ({
      ...news,
      author: author._id
    }));

    // Вставить новости
    const result = await News.insertMany(newsWithAuthor);
    console.log(`✅ Добавлено ${result.length} новостей`);

    // Статистика
    const approved = result.filter(n => n.status === 'approved').length;
    
    console.log(`\n📊 Статистика:`);
    console.log(`   Одобренных: ${approved}`);
    console.log(`   Всего: ${result.length}`);

    process.exit(0);
  } catch (error) {
    console.error('❌ Ошибка:', error);
    process.exit(1);
  }
}

seedNews();


